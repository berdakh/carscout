def build():
    cars = []
    for (make, model, body, seg, y0, y1, prices, rel, repair, ins, mpg, dep, issues, note) in ROWS:
        cars.append({
            "id": f"{make}-{model}".lower().replace(" ", "-"),
            "make": make, "model": model, "body": body, "segment": seg,
            "years": [y0, y1],
            "price_by_age": {str(k): v for k, v in sorted(prices.items())},
            "reliability": rel,
            "annual_repair_cost": repair,
            "insurance_tier": ins,
            "mpg_combined": mpg,
            "depreciation_yearly_pct": dep,
            "known_issues": issues,
            "novice_notes": note,
        })
    out = {
        "_note": "Approximate 2026 US dealer retail asking prices by vehicle age for average mileage and clean title. Seeded from general market knowledge; refresh with scripts/build_seed.py. Reliability is 1-5. mpg_combined for EVs is MPGe.",
        "_updated": "2026-10",
        "cars": cars,
    }
    Path(__file__).resolve().parent.parent.joinpath("data", "seed_cars.json").write_text(json.dumps(out, indent=1))
    print(f"wrote {len(cars)} models")

if __name__ == "__main__":
    build()
